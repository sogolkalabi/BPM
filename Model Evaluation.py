import pm4py

"""# Importing Files

**XES Files**

IEEE XES is a standard format describing how event logs are stored. Note that IEEE XES Event Logs are imported into a Pandas dataframe object.
"""

log = pm4py.read_xes('/content/running-example (1).xes')

"""**CSV Files**

A lot of event logs are actually stored in a **CSV** file. In general, there is two ways to deal with CSV files in pm4py:


1.   Import the CSV into a pandas DataFrame
2.   Convert the CSV into an event log object (similar to the result of the IEEE XES importer presented in the previous section); In this case, the first step is to import the CSV file using pandas (similar to the previous bullet) and subsequently converting it to the event log object.
"""

import pandas as pd
dataframe = pd.read_csv('/content/PurchasingExample.csv', sep=',')
dataframe

dataframe=pm4py.format_dataframe(dataframe,case_id="Case ID", activity_key="Activity",timestamp_key="Complete Timestamp",start_timestamp_key="Start Timestamp" )
dataframe

event_log = pm4py.convert_to_event_log(dataframe)

event_log

"""# Exporting files

**to IEEE XES**
"""

pm4py.write_xes(event_log, 'exported.xes')

"""**to CSV**"""

dataframe = pm4py.convert_to_dataframe(event_log)
dataframe.to_csv('exported.csv')

"""# Filtering Event Data

**Start & end Activities**
"""

start_activities = pm4py.get_start_activities(event_log)
end_activities = pm4py.get_end_activities(event_log)
print("Start activities: {}\nEnd activities: {}".format(start_activities, end_activities))

"""**variants**

To retrieve the variants from the log:
"""

variants = pm4py.get_variants(log)
variants

"""To filter on a given collection of variants:"""

variants = pm4py.filter_variants(log, ["A,B,C,D", "A,E,F,G", "A,C,D"])

"""**time frame**

One might be interested in only keeping the traces that are contained in a specific interval, e.g. 09 March 2011 and 18 January 2012.
"""

filtered_log = pm4py.filter_time_range(log, "2011-03-09 00:00:00", "2012-01-18 23:59:59", mode='traces_contained')

"""method to keep the events that are contained in specific timeframe."""

filtered_log = pm4py.filter_time_range(log, "2011-03-09 00:00:00", "2012-01-18 23:59:59", mode='events')

"""**case performance**

This filter permits to keep only traces with duration that is inside a specified interval. In the examples, traces between 1 and 10 days are kept. Note that the time parameters are given in seconds.
"""

filtered_log = pm4py.filter_case_performance(log, 86400, 864000)
filtered_log

"""# Process Discovery"""

filtered_log = pm4py.filter_end_activities(event_log, ["Pay Invoice"])

"""**Petri nets**

**Alpha Miner**

The alpha miner is one of the most known Process Discovery algorithm and is able to find:

A Petri net model where all the transitions are visible and unique and correspond to classified events (for example, to activities).
An initial marking that describes the status of the Petri net model when a execution starts.
A final marking that describes the status of the Petri net model when a execution ends.
"""

net, initial_marking, final_marking = pm4py.discover_petri_net_alpha(filtered_log)

pm4py.view_petri_net(net, initial_marking, final_marking)

"""**Huristic Miner**"""

net,im,fm=pm4py.discover_petri_net_heuristics(filtered_log, dependency_threshold=0.99)

pm4py.view_petri_net(net,im,fm)

"""**Inductive Miner**"""

net_f, im_f, fm_f = pm4py.discover_petri_net_inductive(filtered_log,0.9, activity_key='concept:name', case_id_key='case:concept:name', timestamp_key='time:timestamp')
pm4py.view_petri_net(net_f, im_f, fm_f)

"""**BPMN**"""

bpmn_model= pm4py.discover_bpmn_inductive(filtered_log,0.4)

pm4py.view_bpmn(bpmn_model)

"""**Process Tree**"""

process_tree= pm4py.discover_process_tree_inductive(filtered_log,0.3)

pm4py.view_process_tree(process_tree)

net1, im1, fm1= pm4py.convert_to_petri_net(process_tree)

"""You can convert process trees to petri net"""

pm4py.view_petri_net(net1,im1,fm1)

"""# Conformance Checking

There are different methods for conformance checking. Here we use Alignments method.
"""

m=pm4py.conformance_diagnostics_alignments( event_log, bpmn_model)
print(m)

"""# Model Evaluation

There are different metrics to evaluate the conformance of process model with the event log such as:
1)fitness



2)Precision
3)Generalization
\4)Simplicity
"""

fitness = pm4py.fitness_alignments(event_log, net, im, fm)
print('fitness is:',fitness)

from pm4py.algo.evaluation.generalization import algorithm as generalization_evaluator
gen = generalization_evaluator.apply(event_log, net, im, fm)
print('generalization evaluation is:', gen)

from pm4py.algo.evaluation.simplicity import algorithm as simplicity_evaluator
simp = simplicity_evaluator.apply(net)
print('simplicity measure is:',simp)